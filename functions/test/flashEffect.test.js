test("flaş: altın değerler (Dart önizlemesiyle aynı)", () => {
  for (const [k, gray, want] of GOLDEN) {
    const { d, F, S } = input();
    FE.flashPixels(d, W, H, 3, F, S, k, gray);
    assert.deepStrictEqual(Array.from(d), want, `k=${k} gray=${gray}`);
  }
});

test("flaş: mulberry32 dizisi sabit (Dart kopyası aynı diziyi üretir)", () => {
  const r = FE._testables.mulberry32(12345);
  assert.deepStrictEqual([r(), r(), r()], [0.9797282677609473,0.3067522644996643,0.484205421525985]);
});

test("flaş: yoğunluk 0 kareye dokunmaz", () => {
  const { d, F, S } = input();
  const before = Array.from(d);
  FE.flashPixels(d, W, H, 3, F, S, 0, false);
  assert.deepStrictEqual(Array.from(d), before);
});

test("flaş: ışık alanı parlatır, ışık almayan yer kararır", () => {
  const W2 = 200, d = new Uint8Array(W2 * 3).fill(120);
  const F = new Float32Array(W2), S = new Float32Array(W2);
  for (let x = 90; x < 110; x++) F[x] = 1; // ortada ışık (kenar karartmasından uzak)
  FE.flashPixels(d, W2, 1, 3, F, S, 1, true);
  assert.ok(d[100 * 3] > 120, `ışıklı ${d[300]}`);
  assert.ok(d[60 * 3] < 120, `ışıksız ${d[180]}`);
});
